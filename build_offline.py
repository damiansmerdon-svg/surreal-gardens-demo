#!/usr/bin/env python3
"""Run after changing any file: writes files.json and sw.js so the walk can be saved on a phone and opened with no signal."""
import hashlib, json, os
skip = {'sw.js', 'files.json', 'build_offline.py', 'README.md'}
files = {}
for d, dirs, names in os.walk('.'):
    dirs[:] = [x for x in dirs if not x.startswith('.')]
    for n in names:
        p = os.path.join(d, n)[2:].replace(os.sep, '/')
        if p in skip or n.startswith('.') or n == 'LICENSE': continue
        b = open(p, 'rb').read(); files[p] = [hashlib.sha1(b).hexdigest()[:12], len(b)]
files = dict(sorted(files.items()))
import datetime
built = (datetime.datetime.utcnow() + datetime.timedelta(hours=10.5)).strftime('%-d %b, %-I:%M %p')      # Adelaide time
doc = json.dumps({'built': built, 'files': files}, separators=(',', ':'))
open('files.json', 'w').write(doc)
open('sw.js', 'w').write('''// Generated by build_offline.py: do not edit. Serves the Mushroom Walk from the copy saved on the phone.
const DOC = %s, FILES = DOC.files, CACHE = 'mushroom-walk';
const keyOf = p => p + '?h=' + FILES[p][0];
self.addEventListener('install', e => { self.skipWaiting(); });
self.addEventListener('activate', e => { e.waitUntil((async () => {
  const c = await caches.open(CACHE), want = new Set(Object.keys(FILES).map(keyOf)), saved = !!(await c.match('__saved'));
  for (const r of await c.keys()) { const u = new URL(r.url); if (u.origin !== location.origin) continue; const k = u.pathname.slice(new URL(self.registration.scope).pathname.length) + u.search; if (k !== '__saved' && !want.has(k)) await c.delete(r); }
  await self.clients.claim();
  if (saved) for (const p of Object.keys(FILES)) { if (await c.match(keyOf(p))) continue; try { const r = await fetch(p, { cache: 'no-store' }); if (r.ok) await c.put(keyOf(p), r); } catch (err) {} }      // a saved phone picks up changed files by itself
})()); });
self.addEventListener('fetch', e => { const req = e.request; if (req.method !== 'GET') return; const u = new URL(req.url), scope = new URL(self.registration.scope);
  if (u.origin !== location.origin) { if (!/fonts\\.(googleapis|gstatic)\\.com$/.test(u.hostname)) return;
    e.respondWith((async () => { const c = await caches.open(CACHE), hit = await c.match(req); if (hit) return hit; try { const r = await fetch(req); c.put(req, r.clone()); return r; } catch (err) { return new Response('', { status: 503 }); } })()); return; }
  if (!u.pathname.startsWith(scope.pathname)) return; let p = u.pathname.slice(scope.pathname.length) || 'index.html';
  if (p === 'files.json') { e.respondWith(new Response(JSON.stringify(DOC), { headers: { 'Content-Type': 'application/json' } })); return; }
  if (!FILES[p]) return;
  e.respondWith((async () => { const c = await caches.open(CACHE), hit = await c.match(keyOf(p)); if (hit) return hit;
    const r = await fetch(req.mode === 'navigate' ? p : req, { cache: 'no-store' }); if (r.ok && r.status === 200) c.put(keyOf(p), r.clone()); return r; })());
});
''' % doc)
print(len(files), 'files', sum(v[1] for v in files.values()) // 1048576, 'MB')
